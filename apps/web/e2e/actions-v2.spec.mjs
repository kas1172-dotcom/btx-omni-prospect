import { expect, test } from '@playwright/test'

async function create(page, title) {
  await page.goto('/#/actions')
  await page.getByLabel('Quick add task').fill(title)
  await page.getByLabel('Quick add task').press('Enter')
  await expect(page.locator('.action-detail').getByLabel('Title', { exact: true })).toHaveValue(title)
  return page.locator('.action-detail')
}

test('inline personal task persists edits, subtasks, cancel undo and completed reopen', async ({ page }) => {
  const title = `Personal review ${crypto.randomUUID()}`
  const detail = await create(page, title)
  await detail.getByLabel('Description', { exact: true }).fill('Evidence review required')
  await detail.getByLabel('Description', { exact: true }).blur()
  await expect(detail.getByText('Saved', { exact: true })).toBeVisible()
  await detail.getByLabel('New subtask').fill('Read evidence')
  await detail.getByRole('button', { name: 'Add subtask' }).click()
  await expect(detail.getByRole('heading', { name: 'Subtasks · 0/1' })).toBeVisible()
  await detail.getByLabel('Subtask title', { exact: true }).fill('Read source evidence')
  await detail.getByLabel('Subtask title', { exact: true }).blur()
  await expect(detail.getByLabel('Done: Read source evidence')).toBeVisible()
  await detail.getByLabel('Done: Read source evidence').check()
  await expect(detail.getByRole('heading', { name: 'Subtasks · 1/1' })).toBeVisible()
  await detail.getByRole('button', { name: 'Remove subtask' }).click()
  await expect(detail.getByRole('button', { name: 'Restore subtask' })).toBeVisible()
  await detail.getByRole('button', { name: 'Restore subtask' }).click()
  await detail.getByRole('button', { name: 'Cancel task' }).click()
  await expect(detail.getByLabel('Status', { exact: true })).toHaveValue('CANCELED')
  await page.locator('.action-undo').getByRole('button', { name: 'Undo' }).click()
  await expect(detail.getByLabel('Status', { exact: true })).toHaveValue('OPEN')
  await detail.getByRole('button', { name: 'Complete', exact: true }).click()
  await expect(detail.getByLabel('Status', { exact: true })).toHaveValue('COMPLETED')
  await detail.getByRole('button', { name: 'Reopen', exact: true }).click()
  await expect(detail.getByLabel('Status', { exact: true })).toHaveValue('IN_PROGRESS')
  await page.reload()
  await expect(detail.getByLabel('Description', { exact: true })).toHaveValue('Evidence review required')
  await expect(detail.getByLabel('Done: Read source evidence')).toBeChecked()
})

test('cancel can reopen after the undo toast expires and Closed keeps its URL key', async ({ page }) => {
  const detail = await create(page, `Reopen later ${crypto.randomUUID()}`)
  await detail.getByRole('button', { name: 'Cancel task' }).click()
  await expect(page.locator('.action-undo')).toBeVisible()
  await expect(page.locator('.action-undo')).toBeHidden({ timeout: 12000 })
  await page.getByRole('button', { name: 'Closed', exact: true }).click()
  await expect(page).toHaveURL(/view=completed/)
  await detail.getByRole('button', { name: 'Reopen', exact: true }).click()
  await expect(detail.getByLabel('Status', { exact: true })).toHaveValue('OPEN')
})

